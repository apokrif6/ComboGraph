const FPinConnectionResponse UEdGraphSchema_ComboGraph::CanCreateConnection(const UEdGraphPin* A,
                                                                            const UEdGraphPin* B) const
{
	if (A->GetOwningNode() == B->GetOwningNode())
	{
		return FPinConnectionResponse(CONNECT_RESPONSE_DISALLOW,
		                              LOCTEXT("PinErrorSameNode", "Can't connect node to itself"));
	}

	const UEdGraphPin* Out = A;
	const UEdGraphPin* In = B;

	const UEdNode_ComboGraphNode* EdNodeOut = Cast<UEdNode_ComboGraphNode>(Out->GetOwningNode());
	const UEdNode_ComboGraphNode* EdNodeIn = Cast<UEdNode_ComboGraphNode>(In->GetOwningNode());

	if (!EdNodeOut || !EdNodeIn)
	{
		return FPinConnectionResponse(CONNECT_RESPONSE_DISALLOW,
		                              LOCTEXT("PinError", "EdNode_ComboGraphNode is invalid"));
	}

	FText ErrorMessage;
	if (!EdNodeOut->ComboGraphNode->CanCreateConnectionTo(EdNodeIn->ComboGraphNode,
	                                                      EdNodeOut->GetOutputPin()->LinkedTo.Num(), ErrorMessage))
	{
		return FPinConnectionResponse(CONNECT_RESPONSE_DISALLOW, ErrorMessage);
	}

	if (!EdNodeIn->ComboGraphNode->CanCreateConnectionFrom(EdNodeOut->ComboGraphNode,
	                                                       EdNodeIn->GetInputPin()->LinkedTo.Num(), ErrorMessage))
	{
		return FPinConnectionResponse(CONNECT_RESPONSE_DISALLOW, ErrorMessage);
	}

	if (EdNodeOut->ComboGraphNode->GetGraph()->bEdgeEnabled)
	{
		return FPinConnectionResponse(CONNECT_RESPONSE_MAKE_WITH_CONVERSION_NODE,
		                              LOCTEXT("PinConnect", "Connect nodes with edge"));
	}

	return FPinConnectionResponse(CONNECT_RESPONSE_MAKE, LOCTEXT("PinConnect", "Connect nodes"));
}

bool UEdGraphSchema_ComboGraph::TryCreateConnection(UEdGraphPin* A, UEdGraphPin* B) const
{
	const UEdNode_ComboGraphNode* NodeA = Cast<UEdNode_ComboGraphNode>(A->GetOwningNode());
	const UEdNode_ComboGraphNode* NodeB = Cast<UEdNode_ComboGraphNode>(B->GetOwningNode());

	for (const UEdGraphPin* TestPin : NodeA->GetOutputPin()->LinkedTo)
	{
		UEdGraphNode* ChildNode = TestPin->GetOwningNode();
		if (UEdNode_ComboGraphEdge* EdNode_Edge = Cast<UEdNode_ComboGraphEdge>(ChildNode))
		{
			ChildNode = EdNode_Edge->GetEndNode();
		}

		if (ChildNode == NodeB)
			return false;
	}

	if (NodeA && NodeB)
	{
		return Super::TryCreateConnection(NodeA->GetOutputPin(), NodeB->GetInputPin());
	}

	return false;
}

bool UEdGraphSchema_ComboGraph::CreateAutomaticConversionNodeAndConnections(UEdGraphPin* A, UEdGraphPin* B) const
{
	UEdNode_ComboGraphNode* NodeA = Cast<UEdNode_ComboGraphNode>(A->GetOwningNode());
	UEdNode_ComboGraphNode* NodeB = Cast<UEdNode_ComboGraphNode>(B->GetOwningNode());

	if (!NodeA || !NodeA->GetOutputPin() || !NodeB || !NodeB->GetInputPin())
		return false;

	const UComboGraph* Graph = NodeA->ComboGraphNode->GetGraph();

	const FVector2D InitPos((NodeA->NodePosX + NodeB->NodePosX) / 2, (NodeA->NodePosY + NodeB->NodePosY) / 2);

	FAssetSchemaAction_ComboGraph_NewEdge Action;
	Action.NodeTemplate = NewObject<UEdNode_ComboGraphEdge>(NodeA->GetGraph());
	Action.NodeTemplate->SetEdge(NewObject<UComboGraphEdge>(Action.NodeTemplate, Graph->EdgeType));
	UEdNode_ComboGraphEdge* EdgeNode = Cast<UEdNode_ComboGraphEdge>(
		Action.PerformAction(NodeA->GetGraph(), nullptr, InitPos, false));

	EdgeNode->CreateConnections(NodeA, NodeB);

	return true;
}

