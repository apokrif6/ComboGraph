void UEdGraphSchema_ComboGraph::GetGraphContextActions(FGraphContextMenuBuilder& ContextMenuBuilder) const
{
	UComboGraph* Graph = CastChecked<UComboGraph>(ContextMenuBuilder.CurrentGraph->GetOuter());

	if (!Graph->NodeType)
		return;

	const FText AddToolTip = LOCTEXT("NewComboGraphNodeTooltip", "Add combo node here :)");

	TSet<TSubclassOf<UComboGraphNode>> Visited;

	FText Desc = Graph->NodeType.GetDefaultObject()->ContextMenuName;

	if (Desc.IsEmpty())
	{
		FString Title = Graph->NodeType->GetName();
		Title.RemoveFromEnd("_C");
		Desc = FText::FromString(Title);
	}

	if (!Graph->NodeType->HasAnyClassFlags(CLASS_Abstract))
	{
		const TSharedPtr<FAssetSchemaAction_ComboGraph_NewNode> NewNodeAction(
			new FAssetSchemaAction_ComboGraph_NewNode(
				LOCTEXT("ComboGraphNodeAction", "Combo Graph Node"), Desc, AddToolTip, 0));
		NewNodeAction->NodeTemplate = NewObject<UEdNode_ComboGraphNode>(ContextMenuBuilder.OwnerOfTemporaries);
		NewNodeAction->NodeTemplate->ComboGraphNode = NewObject<UComboGraphNode>(
			NewNodeAction->NodeTemplate, Graph->NodeType);
		NewNodeAction->NodeTemplate->ComboGraphNode->Graph = Graph;
		ContextMenuBuilder.AddAction(NewNodeAction);

		Visited.Add(Graph->NodeType);
	}

	for (TObjectIterator<UClass> It; It; ++It)
	{
		if (It->IsChildOf(Graph->NodeType) && !It->HasAnyClassFlags(CLASS_Abstract) && !Visited.Contains(*It))
		{
			TSubclassOf<UComboGraphNode> NodeType = *It;

			//Remove REINST assets caused by recompiling blueprint
			//Remove SKEL assets which are SkeletonClass generated by BlueprintCompilationManager
			if (It->GetName().StartsWith("REINST") || It->GetName().StartsWith("SKEL"))
				continue;

			if (!Graph->GetClass()->IsChildOf(NodeType.GetDefaultObject()->CompatibleGraphType))
				continue;

			Desc = NodeType.GetDefaultObject()->ContextMenuName;

			if (Desc.IsEmpty())
			{
				FString Title = NodeType->GetName();
				Title.RemoveFromEnd("_C");
				Desc = FText::FromString(Title);
			}

			TSharedPtr<FAssetSchemaAction_ComboGraph_NewNode> Action(
				new FAssetSchemaAction_ComboGraph_NewNode(
					LOCTEXT("ComboGraphNodeAction", "Combo Graph Node"), Desc, AddToolTip, 0));
			Action->NodeTemplate = NewObject<UEdNode_ComboGraphNode>(ContextMenuBuilder.OwnerOfTemporaries);
			Action->NodeTemplate->ComboGraphNode = NewObject<UComboGraphNode>(Action->NodeTemplate, NodeType);
			Action->NodeTemplate->ComboGraphNode->Graph = Graph;
			ContextMenuBuilder.AddAction(Action);

			Visited.Add(NodeType);
		}
	}
}

